import { readFileSync } from "node:fs";
import { connectBot } from "../../../packages/bot-client/src/connection.ts";
import { openNodeSocket } from "../../../packages/bot-client/src/node-socket.ts";
import { createBotContext, estimateSeconds, groundActions, placeOfPickup } from "../../../src/shared/bots/actions.ts";
import { buildWorldState } from "../../../src/shared/bots/state.ts";
import { retrieve } from "../../../src/shared/bots/goals.ts";
import { chooseGoal } from "../../../src/shared/bots/goap.ts";
const token = (process.env.CE_TOKEN ?? "").trim();
const session = await connectBot({ url: "ws://localhost:4173", token, name: "dev-probe", role: "qa", openSocket: openNodeSocket, onLog: () => {} });
const world = session.world;
const sleep = (ms: number) => new Promise<void>((r) => setTimeout(r, ms));
const started = Date.now();
while ((!world.self() || !world.sceneGraph()) && Date.now() - started < 8000) await sleep(50);
const self = world.self()!;
const graph = world.sceneGraph()!;
const at = world.placeOf(self)?.id ?? "outside";
console.log("self", self.x.toFixed(2), self.z.toFixed(2), "at", at, "pickups", world.pickups().length, "placements", world.pickupPlacements().length, "held", world.keys().join(",") || "none");
const placements = world.pickupPlacements();
const item = placements.find((p: any) => p.id === "cover-crate-2-1-71-9");
console.log("item", item ? "present" : "MISSING", item ? placeOfPickup(graph, item) : "-");
const goal = retrieve("cover-crate-2-1-71-9", "outside");
const doors = world.doors().map((d) => ({ id: d.id, open: d.open, locked: d.locked }));
const state = buildWorldState({ at, pickups: [...world.pickups()], heldKeys: [...world.keys()], doors });
const ctx = createBotContext(graph, placements as never);
const actions = groundActions(graph, placements as never, [goal]);
console.log("pickup actions", actions.filter((a) => a.id.startsWith("pickup:")).map((a) => a.id));
const plan = chooseGoal(state, [goal], actions, ctx, { minCost: ctx.minActionS, heuristic: estimateSeconds(goal, ctx, placements as never), maxExpand: 2000, now: () => Date.now() });
console.log("plan", plan?.steps, "expanded", plan?.expanded);
session.close();
