import { readFileSync } from "node:fs";
import { connectBot } from "../../../packages/bot-client/src/connection.ts";
import { openNodeSocket } from "../../../packages/bot-client/src/node-socket.ts";
import { createBotContext, estimateSeconds } from "../../../src/shared/bots/actions.ts";
import { buildWorldState } from "../../../src/shared/bots/state.ts";
import { standAt } from "../../../src/shared/bots/goals.ts";
import { chooseGoal } from "../../../src/shared/bots/goap.ts";
import { groundActions } from "../../../src/shared/bots/actions.ts";
import { resolveStand, type DoorView } from "../../../src/shared/nav/stand.ts";
const token = readFileSync("/home/tim/.config/ce-arena/qa-token.pem", "utf8").trim();
const session = await connectBot({ url: "ws://127.0.0.1:4173", token, name: "dev-probe", role: "qa", openSocket: openNodeSocket, onLog: () => {} });
const world = session.world;
const sleep = (ms: number) => new Promise<void>((r) => setTimeout(r, ms));
const started = Date.now();
while ((!world.self() || !world.sceneGraph()) && Date.now() - started < 5000) await sleep(50);
const graph = world.sceneGraph()!;
const self = world.self()!;
const at = world.placeOf(self)?.id ?? "outside";
const doors = world.doors().map((d) => ({ id: d.id, open: d.open, locked: d.locked }));
const views: DoorView[] = [];
for (const row of world.doors()) {
  const body = world.doorBody(row.id);
  if (body) views.push({ ...body, open: row.open, locked: row.locked });
}
const target = { kind: "door" as const, doorId: "brutalist-building-1-cbake.room-a-1-5-8-9-3.door-1-1-9-22-5", side: "out" as const };
const stand = resolveStand(target, graph, views, { from: self })!;
console.log("live at", at, "self", self.x.toFixed(2), self.z.toFixed(2), "doors open", doors.filter((d) => d.open).length);
console.log("stand", stand.place, stand.x.toFixed(2), stand.z.toFixed(2));
const ctx = createBotContext(graph, world.pickupPlacements() as never);
console.log("routeCost outside->e1@0", ctx.routeCost("outside", "brutalist-building-1-cbake.e1@0", buildWorldState({ at: "outside", pickups: [], doors })));
console.log("routeCost e1@4->floor-5 hall", ctx.routeCost("brutalist-building-1-cbake.e1@4", "brutalist-building-1-cbake.floor-5.hall", buildWorldState({ at: "outside", pickups: [], doors })));
const state = buildWorldState({ at, pickups: [...world.pickups()], heldKeys: [...world.keys()], doors });
const goal = standAt(target);
const h = estimateSeconds(goal, ctx, world.pickupPlacements() as never, stand);
console.log("h(start)", h(state));
const actions = groundActions(graph, world.pickupPlacements() as never, [goal], stand);
console.log("actions", actions.length, "rides", actions.filter((a) => a.id.startsWith("ride:")).length);
const slim = actions.filter((a) => !a.id.startsWith("ride:") || a.id.includes("brutalist-building-1-cbake.e1:"));
console.log("slim actions", slim.length, "rides", slim.filter((a) => a.id.startsWith("ride:")).length);
const t0 = Date.now();
const plan = chooseGoal(state, [goal], slim, ctx, { minCost: ctx.minActionS, heuristic: h, maxExpand: 3000, now: () => Date.now() });
console.log("slim plan ms", Date.now() - t0);
console.log("plan", plan?.steps, "expanded", plan?.expanded);
session.close();
