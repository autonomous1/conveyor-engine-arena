import { loadArena } from "../../../src/server/world-loader.ts";
import { createBotContext, estimateSeconds, groundActions } from "../../../src/shared/bots/actions.ts";
import { buildWorldState } from "../../../src/shared/bots/state.ts";
import { reach } from "../../../src/shared/bots/goals.ts";
import { chooseGoal } from "../../../src/shared/bots/goap.ts";
const loaded = loadArena();
const graph = loaded.sceneGraph!;
const goal = reach("brutalist-building-1-cbake.e1@4");
const doors = (loaded.view.doors ?? []).map((d: any) => ({ id: d.id, open: d.open === true, locked: d.locked === true }));
const state = buildWorldState({ at: "outside", pickups: (loaded.view.pickups ?? []).map((p: any) => p.id), doors });
const ctx = createBotContext(graph, loaded.view.pickups as any ?? []);
const h = estimateSeconds(goal, ctx, (loaded.view.pickups as any) ?? []);
console.log("h(start)", h(state));
const actions = groundActions(graph, (loaded.view.pickups as any) ?? [], [goal]);
console.log("ride actions", actions.filter((a) => a.id.includes("ride")).length, "goTo e1@0", actions.some((a) => a.id === "goTo:brutalist-building-1-cbake.e1@0"));
const withH = chooseGoal(state, [goal], actions, ctx, { minCost: ctx.minActionS, heuristic: h, maxExpand: 3000, now: () => Date.now() });
console.log("plan with estimateSeconds", withH?.steps, withH?.expanded);
const noH = chooseGoal(state, [goal], actions, ctx, { minCost: ctx.minActionS, maxExpand: 3000, now: () => Date.now() });
console.log("plan without heuristic", noH?.steps, noH?.expanded);
