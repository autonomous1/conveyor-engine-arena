import { loadArena } from "../../../src/server/world-loader.ts";
import { createBotContext, estimateSeconds, groundActions } from "../../../src/shared/bots/actions.ts";
import { buildWorldState } from "../../../src/shared/bots/state.ts";
import { retrieve } from "../../../src/shared/bots/goals.ts";
import { chooseGoal } from "../../../src/shared/bots/goap.ts";
import { placeOfPickup } from "../../../src/shared/bots/actions.ts";
const loaded = loadArena();
const graph = loaded.sceneGraph!;
const placements = (loaded.view.pickups ?? []) as any[];
const item = placements.find((p: any) => p.id === "cover-crate-2-1-71-9");
console.log("item", item && { x: (item.minX + item.maxX) / 2, z: (item.minZ + item.maxZ) / 2, y: item.minY });
console.log("placeOfPickup", item && placeOfPickup(graph, item));
const goal = retrieve("cover-crate-2-1-71-9", "outside");
const doors = (loaded.view.doors ?? []).map((d: any) => ({ id: d.id, open: d.open === true, locked: d.locked === true }));
const state = buildWorldState({ at: "outside", pickups: placements.map((p: any) => p.id), doors });
const ctx = createBotContext(graph, placements);
const place = item ? placeOfPickup(graph, item) : "outside";
console.log("routeCost outside->place", ctx.routeCost("outside", place, state));
const actions = groundActions(graph, placements, [goal]);
console.log("pickup actions", actions.filter((a) => a.id.startsWith("pickup:")).map((a) => a.id));
console.log("goTo place grounded", actions.some((a) => a.id === `goTo:${place}`));
const plan = chooseGoal(state, [goal], actions, ctx, { minCost: ctx.minActionS, heuristic: estimateSeconds(goal, ctx, placements), maxExpand: 2000, now: () => Date.now() });
console.log("plan", plan?.steps, "expanded", plan?.expanded);
console.log("pickup usable", actions.filter((a) => a.id.startsWith("pickup:")).map((a) => ({ id: a.id, usable: a.usable ? a.usable(state, ctx) : true })));
